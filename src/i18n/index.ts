const catalogues: Record<UiLang, Dict> = { fa, de, en };

export type TKey = keyof typeof fa & string;

export function translate(lang: UiLang, key: TKey): string {
  return catalogues[lang][key] ?? fa[key] ?? key;
}

export function dirFor(lang: UiLang): 'rtl' | 'ltr' {
  return lang === 'fa' ? 'rtl' : 'ltr';
}

/* Legacy-compatible localStorage keys for language settings */
export const LS_LEARNING_LANG = 'learningLang';
export const LS_UI_LANG = 'uiLang';

export function detectUiLang(): UiLang {
  const saved = localStorage.getItem(LS_UI_LANG);
  if (saved === 'fa' || saved === 'de' || saved === 'en') return saved;
  const nav = navigator.language?.slice(0, 2);
  if (nav === 'fa') return 'fa';
  if (nav === 'de') return 'de';
  return 'fa'; // Persian is the default UI language (product decision)
}
